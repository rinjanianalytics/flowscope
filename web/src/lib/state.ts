// State of the visualize page, as stored in the URL.

import LZString from "lz-string";
import type { Units } from "./api";
import type { GraphType } from "./graph-types";

export type VisualizeState = {
  graphType: GraphType;
  start: string;
  end: string;
  humanStart: string;
  humanEnd: string;
  dimensions: string[];
  limit: number;
  limitType: string;
  "truncate-v4": number;
  "truncate-v6": number;
  filter: string;
  units: Units;
  bidirectional: boolean;
  previousPeriod: boolean;
};

const statePrefixV1 = "v1-";

const unserialize = (serialized: string) => {
  if (serialized.startsWith(statePrefixV1)) {
    return LZString.decompressFromEncodedURIComponent(
      serialized.substring(statePrefixV1.length),
    );
  }
  // URL generated by a previous implementation
  return LZString.decompressFromBase64(serialized);
};

export const decodeState = (
  serialized: string | null | undefined,
): VisualizeState | null => {
  try {
    if (!serialized) return null;
    const unserialized = unserialize(serialized);
    if (!unserialized) return null;
    return JSON.parse(unserialized);
  } catch (error) {
    console.error("cannot decode state:", error);
    return null;
  }
};

export const encodeState = (state: VisualizeState | null) => {
  if (state === null) return "";
  return (
    statePrefixV1 +
    LZString.compressToEncodedURIComponent(
      JSON.stringify(state, Object.keys(state).sort()),
    )
  );
};

/** Deep equality for the plain values stored in a state. */
export const isEqual = (a: unknown, b: unknown): boolean => {
  if (a === b) return true;
  if (typeof a !== "object" || typeof b !== "object" || !a || !b) return false;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  const ka = Object.keys(a as object);
  const kb = Object.keys(b as object);
  return (
    ka.length === kb.length &&
    ka.every((k) =>
      isEqual(
        (a as Record<string, unknown>)[k],
        (b as Record<string, unknown>)[k],
      ),
    )
  );
};
